"""Audit-risk model: XGBoost trained on SYNTHETIC data. Demo only.

Honesty label (also shown in the dashboard): this model is trained on a
synthetic dataset of ~4,000 companies whose risk labels were generated by a
transparent rule plus noise. It demonstrates the shape of the product feature,
not real audit outcomes. No real taxpayer data was used or is available.

The label rule (transparent, in generate_dataset):
  risk_signal = 0.35 * claim_size_pct + 0.25 * (1 - documentation_completeness)
              + 0.25 * (1 - ledger_validity) + 0.15 * aggressive_position
  label = 1 (high audit risk) if risk_signal + noise > threshold
"""
import os

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import train_test_split
from xgboost import XGBClassifier

MODEL_PATH = os.path.join(os.path.dirname(__file__), "risk_model.json")
SEED = 41

FEATURES = ["claim_size_pct", "qualified_share", "documentation_completeness",
            "ledger_validity", "aggressive_position", "prior_claims",
            "industry_risk"]


def generate_dataset(n: int = 4000, seed: int = SEED) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    df = pd.DataFrame({
        "claim_size_pct": rng.beta(2, 8, n) * 0.6,          # claim as % of revenue
        "qualified_share": rng.beta(5, 2, n),               # qualified/total spend
        "documentation_completeness": rng.beta(4, 2, n),    # 0-1
        "ledger_validity": rng.beta(8, 2, n),               # 0-1 chain integrity
        "aggressive_position": rng.integers(0, 2, n),       # binary
        "prior_claims": rng.poisson(2, n),                  # count
        "industry_risk": rng.choice([0.05, 0.1, 0.25, 0.4], n,
                                    p=[0.3, 0.35, 0.25, 0.1]),
    })
    signal = (0.35 * (df.claim_size_pct / 0.6)
              + 0.25 * (1 - df.documentation_completeness)
              + 0.25 * (1 - df.ledger_validity)
              + 0.15 * df.aggressive_position
              + 0.10 * df.industry_risk
              + rng.normal(0, 0.08, n))  # noise
    df["high_risk"] = (signal > np.quantile(signal, 0.75)).astype(int)
    return df


def train(force: bool = False) -> dict:
    """Train on synthetic data, save model, return holdout metrics."""
    if os.path.exists(MODEL_PATH) and not force:
        return {"status": "already trained", "model_path": MODEL_PATH}
    df = generate_dataset()
    X = df[FEATURES]
    y = df["high_risk"]
    Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.25,
                                          random_state=SEED, stratify=y)
    model = XGBClassifier(
        n_estimators=200, max_depth=3, learning_rate=0.1,
        subsample=0.9, colsample_bytree=0.9,
        eval_metric="logloss", random_state=SEED)
    model.fit(Xtr, ytr)
    model.save_model(MODEL_PATH)
    acc = float((model.predict(Xte) == yte).mean())
    auc = float(roc_auc_score(yte, model.predict_proba(Xte)[:, 1]))
    return {"status": "trained", "model_path": MODEL_PATH,
            "rows": len(df), "holdout_accuracy": round(acc, 3),
            "holdout_auc": round(auc, 3)}


def _load():
    from xgboost import XGBClassifier
    m = XGBClassifier()
    m.load_model(MODEL_PATH)
    return m


def score(features: dict) -> dict:
    """Return audit-risk probability for one company.

    Trains on first use if the model file is missing, so a clean clone works.
    """
    if not os.path.exists(MODEL_PATH):
        train()
    model = _load()
    row = pd.DataFrame([{f: float(features.get(f, _default(f))) for f in FEATURES}])
    proba = float(model.predict_proba(row)[0][1])
    return {"audit_risk_probability": round(proba, 4),
            "model": "XGBoost trained on SYNTHETIC data — for demonstration only",
            "features_used": row.iloc[0].to_dict()}


def _default(f: str) -> float:
    # Reasonable mid-range defaults when the caller doesn't supply a feature.
    return {"claim_size_pct": 0.05, "qualified_share": 0.5,
            "documentation_completeness": 0.7, "ledger_validity": 1.0,
            "aggressive_position": 0.0, "prior_claims": 1.0,
            "industry_risk": 0.1}.get(f, 0.0)


def default_features_from_ledger(qualified_expense_total: float,
                                 revenue_estimate: float,
                                 doc_completeness: float,
                                 ledger_valid: bool) -> dict:
    """Derive risk features from the actual ledger, so the demo feeds real data
    into the (synthetic) model."""
    share = (qualified_expense_total / revenue_estimate) if revenue_estimate else 0.0
    return {"claim_size_pct": min(share, 1.0),
            "qualified_share": 0.5,
            "documentation_completeness": doc_completeness,
            "ledger_validity": 1.0 if ledger_valid else 0.2,
            "aggressive_position": 0,
            "prior_claims": 1,
            "industry_risk": 0.1}
